
from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd
import seaborn as sns


def _prepare_output_dir(output_dir: Path) -> None:
    """Create the output directory if it does not exist."""

    output_dir.mkdir(parents=True, exist_ok=True)


def _save_figure(
    fig: plt.Figure,
    output_dir: Path,
    filename: str,
) -> None:
    """Save a figure with consistent output settings."""

    _prepare_output_dir(output_dir)

    fig.savefig(
        output_dir / filename,
        dpi=300,
        bbox_inches="tight",
    )


def plot_monthly_revenue(
    monthly_sales: pd.DataFrame,
    output_dir: Path,
) -> None:
    """Plot monthly revenue trends."""

    data = monthly_sales.copy()
    data["month"] = data["order_month"].astype(str)

    fig, ax = plt.subplots(figsize=(12, 6))

    sns.lineplot(
        data=data,
        x="month",
        y="revenue_mad",
        marker="o",
        ax=ax,
    )

    ax.set(
        title="Monthly Revenue Trend",
        xlabel="Month",
        ylabel="Revenue (MAD)",
    )
    ax.tick_params(axis="x", rotation=45)
    ax.grid(axis="y", alpha=0.3)

    fig.tight_layout()
    _save_figure(fig, output_dir, "monthly_revenue.png")
    plt.show()
    plt.close(fig)


def plot_category_revenue(
    category_performance: pd.DataFrame,
    output_dir: Path,
) -> None:
    """Compare revenue across product categories."""

    data = category_performance.sort_values(
        "revenue_mad",
        ascending=False,
    ).copy()

    fig, ax = plt.subplots(figsize=(11, 6))

    sns.barplot(
        data=data,
        x="revenue_mad",
        y="category",
        ax=ax,
    )

    ax.set(
        title="Revenue by Product Category",
        xlabel="Revenue (MAD)",
        ylabel="Category",
    )
    ax.grid(axis="x", alpha=0.3)

    fig.tight_layout()
    _save_figure(fig, output_dir, "category_revenue.png")
    plt.show()
    plt.close(fig)


def plot_top_cities(
    city_performance: pd.DataFrame,
    output_dir: Path,
    top_n: int = 10,
) -> None:
    """Plot the top cities by delivered sales revenue."""

    data = city_performance.nlargest(
        top_n,
        "revenue_mad",
    ).sort_values("revenue_mad", ascending=True)

    fig, ax = plt.subplots(figsize=(11, 6))

    sns.barplot(
        data=data,
        x="revenue_mad",
        y="shipping_city",
        ax=ax,
    )

    ax.set(
        title=f"Top {top_n} Cities by Revenue",
        xlabel="Revenue (MAD)",
        ylabel="Shipping City",
    )
    ax.grid(axis="x", alpha=0.3)

    fig.tight_layout()
    _save_figure(fig, output_dir, "top_cities_revenue.png")
    plt.show()
    plt.close(fig)


